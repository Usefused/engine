import { createServer } from "vite";
import { readFileSync, readdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ui = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = { openapi: "3.1.0", info: { title: "Synthetic billing", version: "v1" }, paths: {}, webhooks: {}, "x-fused-webhook": { auth_type: "none" } };
const state = { document: source, revision: 1, mode: "success", plans: new Map(), calls: [] };

// API fixtures are in-memory only, so browser verification cannot mutate a real service or bucket.
function reply(response, body, status = 200) { response.statusCode = status; response.setHeader("Content-Type", "application/json"); response.end(JSON.stringify(body)); }

// Bound synthetic request reads before JSON parsing, mirroring the production editor's admission budget.
async function readBody(request) {
  let body = "";
  for await (const chunk of request) {
    body += chunk;
    // A fixture should not become an unbounded local upload server.
    if (body.length > 5 * 1024 * 1024) throw new Error("Fixture request too large");
  }
  return JSON.parse(body || "{}");
}

// The display DTO deliberately differs from the complete draft so tests exercise the lazy read boundary.
function service() {
  const webhooks = Object.entries(state.document.webhooks).flatMap(([name, item]) => Object.entries(item).map(([method, operation]) => ({ id: name + method, name, method: method.toUpperCase(), description: operation.summary ?? operation.description })));
  return { id: "fixture-service", name: "Synthetic billing", slug: "synthetic-billing", is_owner: true, is_public: false, current_service_version: "v1", webhook_count: webhooks.length, webhooks, auth_configs: [] };
}

// This fixture accepts JSON generated by the real builder; YAML upload returns a fixed synthetic parser result.
function plan(input) {
  const document = input.source_content.startsWith("{") ? JSON.parse(input.source_content) : { ...source, webhooks: { "imported.event": { post: { summary: "Imported event", responses: { "200": { description: "Accepted" } } } } } };
  const id = `fixture-plan-${state.plans.size + 1}`;
  state.plans.set(id, { document, expected: input.expected_target });
  const before = Object.keys(state.document.webhooks);
  const after = Object.keys(document.webhooks);
  return { plan_id: id, review_hash: "fixture-review", service_id: "fixture-service", name: "Synthetic billing", is_new_service: false, action: "update_version", target_version: "v1", target_type: "webhooks", expected_target: input.expected_target, webhook_draft: { source_content: JSON.stringify(document) }, diff: { added: after.filter((name) => !before.includes(name)).length, removed: before.filter((name) => !after.includes(name)).length, changed: 0, removed_names: before.filter((name) => !after.includes(name)), settings_changed: JSON.stringify(document["x-fused-webhook"]) !== JSON.stringify(state.document["x-fused-webhook"]) } };
}

// Failure scenarios exercise client recovery only; they make no network call to Registry or Engine.
function apply(input, response) {
  const reviewed = state.plans.get(input.plan_id);
  // The synthetic stale outcome is a definitive pre-commit conflict.
  if (state.mode === "stale") return reply(response, { error: { code: "IMPORT_TARGET_CHANGED", message: "The destination revision changed. Reload and review again.", phase: "registry_apply", commit_state: "not_committed", operation_id: input.plan_id } }, 409);
  state.document = reviewed.document; state.revision++;
  // Simulate a committed response lost in transit; the next status read remains authoritative.
  if (state.mode === "uncertain") return reply(response, { error: { code: "IMPORT_OUTCOME_UNKNOWN", message: "Connection interrupted after apply.", phase: "registry_apply", commit_state: "unknown", operation_id: input.plan_id } }, 502);
  return reply(response, { status: "applied", service_id: "fixture-service", service_version_id: "fixture-version", version: "v1", revision: state.revision, is_new_service: false });
}

// A closed route map ensures unexpected bucket or workspace calls are visible as test failures.
async function handle(request, response, next) {
  const route = request.url.split("?")[0];
  const routes = {
    "/fixture/service": () => reply(response, service()),
    "/fixture/state": () => reply(response, { revision: state.revision, calls: state.calls }),
    "/fixture/mode": async () => { state.mode = (await readBody(request)).mode; reply(response, { ok: true }); },
    "/graphql": () => reply(response, { data: { serviceWebhookEditor: { service_id: "fixture-service", service_version_id: "fixture-version", revision: state.revision, source_content: JSON.stringify(state.document) } } }),
    "/engine/graphql": () => reply(response, { data: { currentActorAccess: { subject_id: "fixture-actor", workspace_id: "fixture-workspace", kind: "owner", authorization_revision: 1, grants: [{ permission: "catalogue.import", resource_type: "WORKSPACE", resource_id: "fixture-workspace" }] } } }),
    "/integrations/import/plan": async () => reply(response, plan(await readBody(request))),
    "/integrations/import/apply": async () => apply(await readBody(request), response),
  };
  // Status reads expose only the synthetic durable outcome of the last fixture apply.
  if (route.startsWith("/integrations/import/operations/")) { state.calls.push(route); return reply(response, { status: "applied", commit_state: "committed", service_id: "fixture-service", service_version_id: "fixture-version", version: "v1", revision: state.revision }); }
  // Only allowlisted test API routes bypass Vite's ordinary static/module serving.
  if (!routes[route]) return next();
  state.calls.push(route);
  return routes[route]();
}

const server = await createServer({ configFile: false, root: path.join(ui, "testdata/webhook-editor"), resolve: { alias: { "~": path.join(ui, "app") } }, esbuild: { jsx: "automatic" }, server: { host: "127.0.0.1", port: 18193, strictPort: true }, plugins: [{ name: "synthetic-webhook-api", configureServer(vite) {
  // Serve the production build's CSS so screenshots test the actual responsive classes.
  vite.middlewares.use((request, response, next) => {
    if (request.url !== "/fixture.css") return next();
    const assets = path.join(ui, "build/client/assets");
    const css = readdirSync(assets).find((file) => file.endsWith(".css"));
    response.setHeader("Content-Type", "text/css"); response.end(readFileSync(path.join(assets, css)));
  });
  vite.middlewares.use((request, response, next) => { handle(request, response, next).catch((error) => reply(response, { error: error.message }, 500)); });
} }] });
await server.listen();
console.log("Synthetic webhook editor fixture: http://127.0.0.1:18193 (no real Registry/Engine)");
